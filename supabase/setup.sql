-- Create a profile automatically on signup (display_name comes from signup metadata).
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, display_name)
  values (new.id, coalesce(nullif(new.raw_user_meta_data->>'display_name', ''), split_part(new.email, '@', 1)))
  on conflict (id) do nothing;
  return new;
end $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute function public.handle_new_user();

-- Atomic checkout: validates stock, writes order + items and decrements stock in one transaction.
create or replace function public.place_order(
  p_customer_name text, p_email text, p_phone text, p_address text,
  p_payment_method text, p_items jsonb
) returns bigint language plpgsql security definer set search_path = public as $$
declare
  v_order_id bigint;
  v_total numeric(12,2) := 0;
  v_item jsonb;
  v_product public.products%rowtype;
  v_qty integer;
begin
  if auth.uid() is null then raise exception 'Please sign in to continue.'; end if;
  if p_payment_method not in ('Cash on delivery','M-Pesa on delivery','M-Pesa via WhatsApp','Bank transfer')
    then raise exception 'Invalid payment method.'; end if;
  if jsonb_array_length(p_items) = 0 or jsonb_array_length(p_items) > 50
    then raise exception 'Add at least one item to your bag.'; end if;

  for v_item in select * from jsonb_array_elements(p_items) loop
    v_qty := (v_item->>'quantity')::integer;
    if v_qty is null or v_qty < 1 then raise exception 'Invalid item quantity.'; end if;
    select * into v_product from public.products
      where id = (v_item->>'id')::bigint and active for update;
    if not found then raise exception 'A product in your bag is no longer available.'; end if;
    if v_product.stock < v_qty then raise exception 'Not enough stock for %.', v_product.name; end if;
    v_total := v_total + v_product.price * v_qty;
  end loop;

  insert into public.orders (user_id, customer_name, email, phone, address, payment_method, total)
  values (auth.uid(), p_customer_name, p_email, p_phone, p_address, p_payment_method, v_total)
  returning id into v_order_id;

  for v_item in select * from jsonb_array_elements(p_items) loop
    v_qty := (v_item->>'quantity')::integer;
    select * into v_product from public.products where id = (v_item->>'id')::bigint;
    update public.products set stock = stock - v_qty where id = v_product.id;
    insert into public.order_items (order_id, product_id, product_name, unit_price, quantity)
    values (v_order_id, v_product.id, v_product.name, v_product.price, v_qty);
  end loop;
  return v_order_id;
end $$;
revoke all on function public.place_order(text, text, text, text, text, jsonb) from public;
grant execute on function public.place_order(text, text, text, text, text, jsonb) to authenticated;

-- Admin-only order status update, with stock restoration when an order is cancelled.
create or replace function public.set_order_status(p_order_id bigint, p_status text)
returns void language plpgsql security definer set search_path = public as $$
declare
  v_old text;
  v_item record;
begin
  if not exists (select 1 from public.profiles where id = auth.uid() and role = 'admin')
    then raise exception 'Administrator access required.'; end if;
  if p_status not in ('Pending','Processing','Shipped','Completed','Cancelled')
    then raise exception 'Invalid order status.'; end if;
  select status into v_old from public.orders where id = p_order_id;
  if not found then raise exception 'Order not found.'; end if;
  if v_old = p_status then return; end if;
  if p_status = 'Cancelled' and v_old <> 'Cancelled' then
    for v_item in select * from public.order_items where order_id = p_order_id loop
      if v_item.product_id is not null then
        update public.products set stock = stock + v_item.quantity where id = v_item.product_id;
      end if;
    end loop;
  elsif v_old = 'Cancelled' then
    for v_item in select * from public.order_items where order_id = p_order_id loop
      if v_item.product_id is not null and
         (select stock from public.products where id = v_item.product_id) < v_item.quantity
        then raise exception 'Not enough stock to reopen order #%.', p_order_id; end if;
    end loop;
    for v_item in select * from public.order_items where order_id = p_order_id loop
      if v_item.product_id is not null then
        update public.products set stock = stock - v_item.quantity where id = v_item.product_id;
      end if;
    end loop;
  end if;
  update public.orders set status = p_status where id = p_order_id;
end $$;
revoke all on function public.set_order_status(bigint, text) from public;
grant execute on function public.set_order_status(bigint, text) to authenticated;

